/**
 * Generates the logo artifacts from the official vector in public/logo-r.svg,
 * so the R path is never copied by hand.
 *
 *   npm run logo:sync
 *
 * Outputs:
 * - components/brand/logo-r-path.ts (path + viewBox for <LogoR />)
 * - app/icon.svg (favicon, R in brand purple)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = readFileSync(resolve(root, "public/logo-r.svg"), "utf8");

const viewBox = source.match(/viewBox="([^"]+)"/)?.[1];
const paths = [...source.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);

if (!viewBox || paths.length !== 1) {
  throw new Error("public/logo-r.svg must have a viewBox and exactly one <path d>.");
}

const [d] = paths;
const BRAND = "#6D28D9";

writeFileSync(
  resolve(root, "components/brand/logo-r-path.ts"),
  `// Generated by scripts/sync-logo.ts from public/logo-r.svg. Do not edit.
export const LOGO_R_VIEWBOX = ${JSON.stringify(viewBox)};
export const LOGO_R_PATH = ${JSON.stringify(d)};
`,
);

writeFileSync(
  resolve(root, "app/icon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="${BRAND}"><path d="${d}"/></svg>
`,
);

console.log("Logo synced: components/brand/logo-r-path.ts, app/icon.svg");
